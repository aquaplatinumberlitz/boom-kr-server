#!/usr/bin/env python3
"""Link the Windows GNU target; the unused iroh DLL must export no Rust symbols.

iroh 1.5 builds both an rlib and a cdylib in one rustc invocation. Cargo links
the rlib into our programs, and none of our packages ships the cdylib. On
MinGW the compiler's autogenerated DLL export list exceeds PE's ordinal range.
Only suppress that unused DLL's export list; all other link arguments (and all
other outputs) go to the ordinary target linker unchanged.
"""
import os
from pathlib import Path
import re
import sys


def main():
    args = sys.argv[1:]
    if '-shared' in args and any(re.fullmatch(r'iroh-[a-f0-9]+\.dll', Path(arg).name) for arg in args):
        defs = [arg for arg in args if arg.startswith('-Wl,') and Path(arg[4:]).name == 'list.def']
        if len(defs) != 1:
            raise SystemExit('Unexpected iroh cdylib export list')
        args[args.index(defs[0])] = '-Wl,--exclude-all-symbols'
    compiler = 'x86_64-w64-mingw32-gcc'
    os.execvp(compiler, [compiler, *args])


if __name__ == '__main__':
    main()
